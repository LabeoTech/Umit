function outFile = pmOptionalCreatedFileOutput(SaveFolder)
%PMOPTIONALCREATEDFILEOUTPUT Create and return an optional file output.

if nargin == 1 && (ischar(SaveFolder) || ...
        (isstring(SaveFolder) && isscalar(SaveFolder))) && ...
        strcmpi(strtrim(char(string(SaveFolder))), 'pipelineInfo')
    outFile = localPipelineInfo();
    return
end

outFile = 'optional_result.txt';
filePath = fullfile(SaveFolder, outFile);
fid = fopen(filePath, 'w');
assert(fid ~= -1, 'Failed to create optional test output.');
cleanupObj = onCleanup(@() fclose(fid));
fwrite(fid, 'created optional output', 'char');
end

function info = localPipelineInfo()
info = PipelineManager.createPipelineInfo( ...
    'pmOptionalCreatedFileOutput', ...
    'Test fixture that creates an optional returned file.');
info = PipelineManager.addInput(info, ...
    'SaveFolder', 'SaveFolder', 'Output folder.', ...
    'kind', 'input', 'position', 1, 'callType', 'positional', ...
    'isData', false);
info = PipelineManager.addOutput(info, ...
    'optionalFile', 'UnknownDataType', 'file', ...
    'Optional returned file.', 'optional_result.txt', 1, ...
    'isData', false, 'isRequired', false);
end
