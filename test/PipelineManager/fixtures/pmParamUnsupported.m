function outData = pmParamUnsupported(data, SaveFolder, varargin) %#ok<INUSD>
%PMPARAMUNSUPPORTED Test fixture with a parameter type the editor cannot render.
%
%   Used by TestPipelineManagerParameterContainer. Declares one 'struct'
%   parameter (as genImageTimeSeriesUMT does); the parameter editors support
%   only logical, numeric (double/single) and char parameters.

if nargin == 1 && (ischar(data) || (isstring(data) && isscalar(data))) && ...
        strcmpi(strtrim(char(string(data))), 'pipelineInfo')
    outData = localPipelineInfo();
    return
end

outData = data;
end

function info = localPipelineInfo()
info = PipelineManager.createPipelineInfo(mfilename, ...
    'Test fixture with a parameter type the editor cannot render.');
info = PipelineManager.addInput(info, ...
    'data', 'ImageTimeSeries', 'Input data.', ...
    'position', 1, 'callType', 'positional', ...
    'isData', true, 'supportsFile', true, 'dataMode', 'either');
info = PipelineManager.addInput(info, ...
    'SaveFolder', 'SaveFolder', 'Output folder.', ...
    'kind', 'input', 'position', 2, 'callType', 'positional', ...
    'isData', false);
info = PipelineManager.addInput(info, 'Options', 'parameter', 'Options struct.', ...
    'kind', 'parameter', 'position', 3, 'callType', 'namevalue', ...
    'default', struct('a', 1), 'allowed', {{}}, 'dataType', 'struct');
info = PipelineManager.addOutput(info, ...
    'outData', 'ImageTimeSeries', 'data', ...
    'Unchanged input.', 'pmParamUnsupported.dat', 1, 'isData', true);
end
