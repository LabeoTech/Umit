function outFile = pmFreshImportInitializer(RawFolder, SaveFolder)
%PMFRESHIMPORTINITIALIZER Test fixture: initializer that runs a fresh import.
%
%   Like a real importer, it calls prepareFreshImport (zip backup, then
%   delete) before writing valid current acquisition metadata.

if nargin == 1 && strcmpi(char(string(RawFolder)), 'pipelineInfo')
    outFile = PipelineManager.createPipelineInfo(mfilename, ...
        'Fresh import, then write valid current acquisition metadata.');
    outFile.freshSaveFolderRole = 'acquisition-initializer';
    outFile = PipelineManager.addInput(outFile, 'RawFolder', 'RawFolder', ...
        'Fixture raw folder.', 'kind', 'input', 'position', 1, ...
        'callType', 'positional', 'isData', false);
    outFile = PipelineManager.addInput(outFile, 'SaveFolder', 'SaveFolder', ...
        'Fixture output folder.', 'kind', 'input', 'position', 2, ...
        'callType', 'positional', 'isData', false);
    outFile = PipelineManager.addOutput(outFile, 'outFile', ...
        'ImageTimeSeries', 'file', 'Fixture data file.', ...
        'imported.dat', 1, 'isData', true, 'saveFileName', '');
    return
end

assert(isfolder(RawFolder));
assert(isfolder(SaveFolder));

prepareFreshImport(SaveFolder, 'backupOpts', 'GENBACKUP', ...
    'Origin', 'pmFreshImportInitializer', 'RecordLedgerEvents', false);

writeTestDat(fullfile(SaveFolder, 'imported.dat'), single(1), 1, 1);

AcqInfoStream = struct( ...
    'Width', 1, ...
    'Height', 1, ...
    'Length', 1, ...
    'FrameRateHz', 1, ...
    'ExposureMsec', 1);
AcqInfoStream = appendImportedChannelInfo(AcqInfoStream, struct( ...
    'DatFile', 'imported.dat', 'Length', 1, 'FrameRateHz', 1));
save(fullfile(SaveFolder, 'AcqInfos.mat'), 'AcqInfoStream', '-mat');
outFile = 'imported.dat';
end
