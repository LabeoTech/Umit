function varargout = pmMissingDeclaredFileEffect(SaveFolder)
%PMMISSINGDECLAREDFILEEFFECT Declare, but do not create, a file effect.

if nargin == 1 && (ischar(SaveFolder) || ...
        (isstring(SaveFolder) && isscalar(SaveFolder))) && ...
        strcmpi(strtrim(char(string(SaveFolder))), 'pipelineInfo')
    varargout{1} = localPipelineInfo();
    return
end

% Intentionally create no file. PipelineManager must reject the missing
% declared effect after this function returns successfully.
varargout = {};
end

function info = localPipelineInfo()
info = PipelineManager.createPipelineInfo( ...
    'pmMissingDeclaredFileEffect', ...
    'Test fixture whose declared file effect is intentionally absent.');
info = PipelineManager.addInput(info, ...
    'SaveFolder', 'SaveFolder', 'Output folder.', ...
    'kind', 'input', 'position', 1, 'callType', 'positional', ...
    'isData', false);
info = PipelineManager.addOutput(info, ...
    'missingEffect', 'UnknownDataType', 'file', ...
    'Pattern intentionally left unmatched.', ...
    'never_created_*.txt', 1, ...
    'isData', false, 'returnsValue', false);
end
