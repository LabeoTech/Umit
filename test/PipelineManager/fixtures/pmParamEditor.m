function outData = pmParamEditor(data, SaveFolder, varargin) %#ok<INUSD>
%PMPARAMEDITOR Test fixture declaring one parameter of every editable kind.
%
%   Used by TestPipelineManagerParameterContainer to drive the embedded and
%   dialog parameter editors. It is never executed by those tests; it only
%   declares parameters:
%       Gain      double, limits [0 10]             -> numeric field
%       Mode      char, {'fast','slow'}             -> dropdown
%       Bands     char, {'a';'b';'c'} (column)      -> multi-select list
%       Exposure  char, {'auto', Inf} (mixed)       -> text field
%       Normalize logical                           -> checkbox

if nargin == 1 && (ischar(data) || (isstring(data) && isscalar(data))) && ...
        strcmpi(strtrim(char(string(data))), 'pipelineInfo')
    outData = localPipelineInfo();
    return
end

outData = data;
end

function info = localPipelineInfo()
info = PipelineManager.createPipelineInfo(mfilename, ...
    'Test fixture declaring one parameter of every editable kind.');
info = PipelineManager.addInput(info, ...
    'data', 'ImageTimeSeries', 'Input data.', ...
    'position', 1, 'callType', 'positional', ...
    'isData', true, 'supportsFile', true, 'dataMode', 'either');
info = PipelineManager.addInput(info, ...
    'SaveFolder', 'SaveFolder', 'Output folder.', ...
    'kind', 'input', 'position', 2, 'callType', 'positional', ...
    'isData', false);
info = PipelineManager.addInput(info, 'Gain', 'parameter', 'Gain factor.', ...
    'kind', 'parameter', 'position', 3, 'callType', 'namevalue', ...
    'default', 1, 'allowed', [0 10], 'dataType', 'double');
info = PipelineManager.addInput(info, 'Mode', 'parameter', 'Processing mode.', ...
    'kind', 'parameter', 'position', 4, 'callType', 'namevalue', ...
    'default', 'fast', 'allowed', {'fast', 'slow'}, 'dataType', 'char');
info = PipelineManager.addInput(info, 'Bands', 'parameter', 'Bands to use.', ...
    'kind', 'parameter', 'position', 5, 'callType', 'namevalue', ...
    'default', {'a'}, 'allowed', {'a'; 'b'; 'c'}, 'dataType', 'char');
info = PipelineManager.addInput(info, 'Exposure', 'parameter', 'Exposure (ms) or auto.', ...
    'kind', 'parameter', 'position', 6, 'callType', 'namevalue', ...
    'default', 'auto', 'allowed', {'auto', Inf}, 'dataType', 'char');
info = PipelineManager.addInput(info, 'Normalize', 'parameter', 'Normalize the output.', ...
    'kind', 'parameter', 'position', 7, 'callType', 'namevalue', ...
    'default', false, 'allowed', [true false], 'dataType', 'logical');
info = PipelineManager.addOutput(info, ...
    'outData', 'ImageTimeSeries', 'data', ...
    'Unchanged input.', 'pmParamEditor.dat', 1, 'isData', true);
end
