function outData = pmMixedReturnedAndFileEffect(data, SaveFolder)
%PMMIXEDRETURNEDANDFILEEFFECT Exercise mixed PipelineManager outputs.

if nargin == 1 && (ischar(data) || (isstring(data) && isscalar(data))) && ...
        strcmpi(strtrim(char(string(data))), 'pipelineInfo')
    outData = localPipelineInfo();
    return
end

localWriteTextFile(fullfile(SaveFolder, 'effect_one.txt'), 'first effect');
localWriteTextFile(fullfile(SaveFolder, 'effect_two.log'), 'second effect');
outData = data + cast(1, 'like', data);
end

function info = localPipelineInfo()
info = PipelineManager.createPipelineInfo( ...
    'pmMixedReturnedAndFileEffect', ...
    'Test fixture with file effects declared before one returned DATA value.');
info = PipelineManager.addInput(info, ...
    'data', 'ImageTimeSeries', 'Input data.', ...
    'position', 1, 'callType', 'positional', ...
    'isData', true, 'supportsFile', false, 'dataMode', 'ram');
info = PipelineManager.addInput(info, ...
    'SaveFolder', 'SaveFolder', 'Output folder.', ...
    'kind', 'input', 'position', 2, 'callType', 'positional', ...
    'isData', false);
info = PipelineManager.addOutput(info, ...
    'effectFiles', 'UnknownDataType', 'file', ...
    'Files written without a MATLAB return value.', ...
    {'effect_one.txt', 'effect_*.log'}, 1, ...
    'isData', false, 'returnsValue', false);
info = PipelineManager.addOutput(info, ...
    'outData', 'ImageTimeSeries', 'data', ...
    'Returned data following the non-returning declaration.', ...
    'mixedOutput.dat', 2, 'isData', true, ...
    'saveFileName', 'mixedOutput.dat');
end

function localWriteTextFile(filePath, contents)
fid = fopen(filePath, 'w');
assert(fid ~= -1, 'Failed to create test file: %s', filePath);
cleanupObj = onCleanup(@() fclose(fid));
fwrite(fid, contents, 'char');
end
