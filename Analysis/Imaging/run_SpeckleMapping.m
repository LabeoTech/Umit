function outData = run_SpeckleMapping(SaveFolder, data, varargin)
%RUN_SPECKLEMAPPING Call SPECKLEMAPPING from the IOI library.
%
%   outData = run_SpeckleMapping(SaveFolder, data)
%   outData = run_SpeckleMapping(SaveFolder, data, 'Name', Value, ...)
%   info    = run_SpeckleMapping('pipelineInfo')
%
%   This wrapper calculates the spatial or temporal standard deviation of a
%   Laser Speckle Contrast Imaging dataset by calling the IOI-library
%   function SPECKLEMAPPING.
%
%   Inputs:
%       SaveFolder - Folder containing the channel files.
%       data       - Execution-mode selector, NOT the processed data.
%                    SPECKLEMAPPING always reads "<channel>.dat" from
%                    SaveFolder, so the content of "data" is never consumed.
%                    Either:
%                    1) Numeric Y x X x T array, selecting standard mode, or
%                    2) .dat filename, selecting RAM-safe mode. A filename
%                       other than "<channel>.dat" raises a warning, because
%                       the run then processes the channel file rather than
%                       the file that was wired in.
%
%   Name-Value parameters:
%       sType     - Standard-deviation mode.
%                   Allowed: 'Spatial', 'Temporal'
%                   Default: 'Temporal'
%
%       channel   - Channel name associated with the speckle data.
%                   Allowed:
%                       'fluo_475', 'fluo', 'red', 'green', 'yellow', 'speckle'
%                   Default: 'speckle'
%
%       bSaveMap  - If true, save the TIFF map generated by SPECKLEMAPPING.
%                   Default: false
%
%       bLogScale - If true, apply -log10 transform.
%                   Default: false
%
%   Output:
%       outData   - UMT struct of kind "image" containing the speckle map.

% Defaults:
default_Output = 'SpeckleMap';

allowedSType = {'Spatial', 'Temporal'};
allowedChannel = {'fluo_475','fluo','red','green','yellow','speckle'};

% -------------------------------------------------------------------------
% pipelineInfo query
% -------------------------------------------------------------------------
if nargin == 1 && (ischar(SaveFolder) || (isstring(SaveFolder) && isscalar(SaveFolder))) ...
        && strcmpi(strtrim(char(string(SaveFolder))), 'pipelineInfo')
    outData = localPipelineInfo();
    return
end

% -------------------------------------------------------------------------
% Input parsing
% -------------------------------------------------------------------------
p = inputParser;
p.FunctionName = mfilename;

addRequired(p, 'SaveFolder', @isfolder);
addRequired(p, 'data', @(x) (isnumeric(x) && ndims(x) == 3) || ...
    ischar(x) || (isstring(x) && isscalar(x)));

addParameter(p, 'sType', 'Temporal', ...
    @(x) (ischar(x) || (isstring(x) && isscalar(x))) && ...
    any(strcmpi(char(string(x)), allowedSType)));

addParameter(p, 'channel', 'speckle', ...
    @(x) (ischar(x) || (isstring(x) && isscalar(x))) && ...
    any(strcmpi(char(string(x)), allowedChannel)));

addParameter(p, 'bSaveMap', false, ...
    @(x) islogical(x) && isscalar(x));

addParameter(p, 'bLogScale', false, ...
    @(x) islogical(x) && isscalar(x));

parse(p, SaveFolder, data, varargin{:});

SaveFolder = p.Results.SaveFolder;
sType = char(string(p.Results.sType));
channel = char(string(p.Results.channel));
bSaveMap = p.Results.bSaveMap;
bLogScale = p.Results.bLogScale;

if isstring(data)
    data = char(data);
end

% -------------------------------------------------------------------------
% Validate file-backed input when applicable
% -------------------------------------------------------------------------
bLowRAMmode = ischar(data);

if bLowRAMmode
    if ~endsWith(data, '.dat', 'IgnoreCase', true)
        data = [data '.dat'];
    end

    dataPath = data;
    if ~isfile(dataPath)
        dataPath = fullfile(SaveFolder, data);
    end

    assert(isfile(dataPath), ...
        'Umitoolbox:run_SpeckleMapping:FileNotFound', ...
        'Input .dat file not found: "%s".', data);

    loadMetaData(dataPath);
end

channelFile = [channel '.dat'];
channelPath = fullfile(SaveFolder, channelFile);
assert(isfile(channelPath), ...
    'Umitoolbox:run_SpeckleMapping:MissingChannelFile', ...
    'Channel file "%s" was not found in "%s".', channelFile, SaveFolder);
loadMetaData(channelPath);

% SPECKLEMAPPING reads the channel file, not "data". Warn when a different
% file was wired in, so a pipeline cannot silently process another channel.
if bLowRAMmode
    [~, inputStem, inputExt] = fileparts(data);
    if ~strcmpi([inputStem inputExt], channelFile)
        warning('Umitoolbox:run_SpeckleMapping:DataInputNotConsumed', ...
            ['Input file "%s" is not the selected channel file "%s". ' ...
             'SpeckleMapping processes "%s", not the file wired into this ' ...
             'step. Set the "channel" parameter to match the intended input.'], ...
            [inputStem inputExt], channelFile, channelFile);
    end
end

% -------------------------------------------------------------------------
% Dispatch
% -------------------------------------------------------------------------
disp(['Calculating ' sType ' standard deviation in ' channel '...'])

try
    outData = SpeckleMapping( ...
        SaveFolder, ...
        sType, ...
        channel, ...
        bSaveMap, ...
        bLogScale, ...
        bLowRAMmode);
catch ME
    ME = addCause(ME, MException( ...
        'Umitoolbox:run_SpeckleMapping:UnknownError', ...
        'Function SpeckleMapping failed.'));
    throw(ME)
end

disp('Finished Speckle Mapping.')

    % =====================================================================
    % Local pipelineInfo factory (nested, shares allowedSType/allowedChannel/
    % default_Output with the parent scope instead of redefining them)
    % =====================================================================
    function info = localPipelineInfo()

        info = PipelineManager.createPipelineInfo( ...
            mfilename, ...
            'Call SPECKLEMAPPING from the IOI library to compute speckle standard-deviation maps.');

        info = PipelineManager.addInput( ...
            info, ...
            'SaveFolder', ...
            'SaveFolder', ...
            'Folder containing the channel files.', ...
            'kind', 'input', ...
            'position', 1, ...
            'callType', 'positional', ...
            'isData', false);

        info = PipelineManager.addInput( ...
            info, ...
            'data', ...
            'ImageTimeSeries', ...
            ['Execution-mode selector, not the processed data. A .dat filename ' ...
             'selects RAM-safe mode and a numeric array selects standard mode; ' ...
             'SpeckleMapping reads "<channel>.dat" from SaveFolder in both cases.'], ...
            'kind', 'input', ...
            'position', 2, ...
            'callType', 'positional', ...
            'isData', true, ...
            'supportsFile', true, ...
            'dataMode', 'either');

        info = PipelineManager.addInput( ...
            info, ...
            'sType', ...
            'parameter', ...
            'Standard-deviation mode.', ...
            'kind', 'parameter', ...
            'default', 'Temporal', ...
            'allowed', allowedSType, ...
            'callType', 'namevalue');

        info = PipelineManager.addInput( ...
            info, ...
            'channel', ...
            'parameter', ...
            'Channel name associated with the speckle data.', ...
            'kind', 'parameter', ...
            'default', 'speckle', ...
            'allowed', allowedChannel, ...
            'callType', 'namevalue');

        info = PipelineManager.addInput( ...
            info, ...
            'bSaveMap', ...
            'parameter', ...
            'If true, save the TIFF map generated by SPECKLEMAPPING.', ...
            'kind', 'parameter', ...
            'default', false, ...
            'allowed', [true false], ...
            'callType', 'namevalue');

        info = PipelineManager.addInput( ...
            info, ...
            'bLogScale', ...
            'parameter', ...
            'If true, apply -log10 transform.', ...
            'kind', 'parameter', ...
            'default', false, ...
            'allowed', [true false], ...
            'callType', 'namevalue');

        info = PipelineManager.addOutput( ...
            info, ...
            'outData', ...
            'ProcessedData', ...
            'data', ...
            'UMT image output containing the computed speckle map.', ...
            default_Output, ...
            1, ...
            'isData', true);

    end

end