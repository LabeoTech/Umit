function outData = run_SpeckleMapping(SaveFolder, data, varargin)
%RUN_SPECKLEMAPPING Call SPECKLEMAPPING from the IOI library.
%
%   outData = run_SpeckleMapping(SaveFolder, data)
%   outData = run_SpeckleMapping(SaveFolder, data, 'Name', Value, ...)
%   info    = run_SpeckleMapping('pipelineInfo')
%
%   This wrapper calculates the spatial or temporal standard deviation of a
%   Laser Speckle Contrast Imaging dataset by calling the IOI-library
%   function SPECKLEMAPPING.
%
%   Inputs:
%       SaveFolder - Folder containing the channel file.
%       data       - Name of the Y-X-T channel .dat file to process, in
%                    SaveFolder. SPECKLEMAPPING reads "<channel>.dat" from
%                    SaveFolder, so the file name must be one of the channel
%                    names below. Arrays, other extensions, other layouts,
%                    and files outside SaveFolder are not supported.
%
%   Name-Value parameters:
%       sType     - Standard-deviation mode.
%                   Allowed: 'Spatial', 'Temporal'
%                   Default: 'Temporal'
%
%       channel   - Channel name of the input file.
%                   Allowed:
%                       'auto', 'fluo_475', 'fluo', 'red', 'green',
%                       'yellow', 'speckle'
%                   Default: 'auto' (the file name of "data"). An explicit
%                   channel that differs from the file name is an error.
%
%       bSaveMap  - If true, save the TIFF map generated by SPECKLEMAPPING.
%                   Default: false
%
%       bLogScale - If true, apply -log10 transform.
%                   Default: false
%
%   Output:
%       outData   - UMT struct of kind "image" containing the speckle map
%                   (one Y-X entry named "SpeckleMap").
%
%   Notes:
%       - The file is processed in chunks by SPECKLEMAPPING (Low-RAM mode is
%         always on).

% Defaults:
default_Output = 'SpeckleMap';

allowedSType = {'Spatial', 'Temporal'};
allowedChannel = {'fluo_475','fluo','red','green','yellow','speckle'};
channelOptions = [{'auto'}, allowedChannel];

% -------------------------------------------------------------------------
% pipelineInfo query
% -------------------------------------------------------------------------
if nargin == 1 && (ischar(SaveFolder) || (isstring(SaveFolder) && isscalar(SaveFolder))) ...
        && strcmpi(strtrim(char(string(SaveFolder))), 'pipelineInfo')
    outData = localPipelineInfo();
    return
end

% -------------------------------------------------------------------------
% Input parsing
% -------------------------------------------------------------------------
p = inputParser;
p.FunctionName = mfilename;

addRequired(p, 'SaveFolder', @isfolder);
addRequired(p, 'data');

addParameter(p, 'sType', 'Temporal', ...
    @(x) (ischar(x) || (isstring(x) && isscalar(x))) && ...
    any(strcmpi(char(string(x)), allowedSType)));

addParameter(p, 'channel', 'auto', ...
    @(x) (ischar(x) || (isstring(x) && isscalar(x))) && ...
    any(strcmpi(char(string(x)), channelOptions)));

addParameter(p, 'bSaveMap', false, ...
    @(x) islogical(x) && isscalar(x));

addParameter(p, 'bLogScale', false, ...
    @(x) islogical(x) && isscalar(x));

parse(p, SaveFolder, data, varargin{:});

SaveFolder = p.Results.SaveFolder;
sType = char(string(p.Results.sType));
channel = char(string(p.Results.channel));
bSaveMap = p.Results.bSaveMap;
bLogScale = p.Results.bLogScale;

% -------------------------------------------------------------------------
% Resolve and validate the input file
% -------------------------------------------------------------------------
assert(ischar(data) || (isstring(data) && isscalar(data)), ...
    'Umitoolbox:run_SpeckleMapping:UnsupportedInputType', ...
    'Input "data" must be the name of a Y-X-T channel .dat file (arrays are not supported).');
data = char(string(data));

[dataFolder, dataStem, dataExt] = fileparts(data);
assert(isempty(dataExt) || strcmpi(dataExt, '.dat'), ...
    'Umitoolbox:run_SpeckleMapping:UnsupportedInputFile', ...
    'Unsupported input file extension "%s". Only .dat files are supported.', dataExt);
dataFile = [dataStem '.dat'];

dataPath = fullfile(dataFolder, dataFile);
if isempty(dataFolder) || ~isfile(dataPath)
    dataPath = fullfile(SaveFolder, dataFile);
end
assert(isfile(dataPath), ...
    'Umitoolbox:run_SpeckleMapping:FileNotFound', ...
    'Input .dat file not found: "%s".', data);

% SPECKLEMAPPING reads "<channel>.dat" from SaveFolder, so the input must be
% that file: a different file would silently process another channel.
assert(strcmpi(iFolderOf(dataPath), iFolderOf(fullfile(SaveFolder, 'x'))), ...
    'Umitoolbox:run_SpeckleMapping:InputNotInSaveFolder', ...
    'Input file "%s" is not in SaveFolder "%s".', dataPath, SaveFolder);

assert(any(strcmpi(dataStem, allowedChannel)), ...
    'Umitoolbox:run_SpeckleMapping:UnsupportedChannelFile', ...
    'The file name "%s" is not a channel name (%s).', dataFile, strjoin(allowedChannel, ', '));

if strcmpi(channel, 'auto')
    channel = lower(dataStem);
else
    assert(strcmpi(channel, dataStem), ...
        'Umitoolbox:run_SpeckleMapping:ChannelMismatch', ...
        'The channel "%s" does not match the input file "%s".', channel, dataFile);
end

assertDatLayout(loadMetaData(dataPath), {{'Y','X','T'}}, 'run_SpeckleMapping');

% -------------------------------------------------------------------------
% Dispatch
% -------------------------------------------------------------------------
disp(['Calculating ' sType ' standard deviation in ' channel '...'])

try
    outData = SpeckleMapping( ...
        SaveFolder, ...
        sType, ...
        channel, ...
        bSaveMap, ...
        bLogScale, ...
        true);
catch ME
    ME = addCause(ME, MException( ...
        'Umitoolbox:run_SpeckleMapping:UnknownError', ...
        'Function SpeckleMapping failed.'));
    throw(ME)
end

disp('Finished Speckle Mapping.')

    % =====================================================================
    % Local pipelineInfo factory (nested, shares allowedSType/allowedChannel/
    % default_Output with the parent scope instead of redefining them)
    % =====================================================================
    function info = localPipelineInfo()

        info = PipelineManager.createPipelineInfo( ...
            mfilename, ...
            'Call SPECKLEMAPPING from the IOI library to compute speckle standard-deviation maps.');
        info.version = '2.0.0';

        info = PipelineManager.addInput( ...
            info, ...
            'SaveFolder', ...
            'SaveFolder', ...
            'Folder containing the channel files.', ...
            'kind', 'input', ...
            'position', 1, ...
            'callType', 'positional', ...
            'isData', false);

        info = PipelineManager.addInput( ...
            info, ...
            'data', ...
            'ImageTimeSeries', ...
            ['Y-X-T channel .dat file (fluo_475, fluo, red, green, yellow or ' ...
             'speckle) in SaveFolder.'], ...
            'kind', 'input', ...
            'position', 2, ...
            'callType', 'positional', ...
            'isData', true, ...
            'supportsFile', true, ...
            'dataMode', 'file');

        info = PipelineManager.addInput( ...
            info, ...
            'sType', ...
            'parameter', ...
            'Standard-deviation mode.', ...
            'kind', 'parameter', ...
            'default', 'Temporal', ...
            'allowed', allowedSType, ...
            'callType', 'namevalue');

        info = PipelineManager.addInput( ...
            info, ...
            'channel', ...
            'parameter', ...
            'Channel name of the input file ("auto" takes it from the file name).', ...
            'kind', 'parameter', ...
            'default', 'auto', ...
            'allowed', channelOptions, ...
            'callType', 'namevalue');

        info = PipelineManager.addInput( ...
            info, ...
            'bSaveMap', ...
            'parameter', ...
            'If true, save the TIFF map generated by SPECKLEMAPPING.', ...
            'kind', 'parameter', ...
            'default', false, ...
            'allowed', [true false], ...
            'callType', 'namevalue');

        info = PipelineManager.addInput( ...
            info, ...
            'bLogScale', ...
            'parameter', ...
            'If true, apply -log10 transform.', ...
            'kind', 'parameter', ...
            'default', false, ...
            'allowed', [true false], ...
            'callType', 'namevalue');

        info = PipelineManager.addOutput( ...
            info, ...
            'outData', ...
            'ProcessedData', ...
            'data', ...
            'UMT image output containing the computed speckle map.', ...
            default_Output, ...
            1, ...
            'isData', true);

    end

end

function folder = iFolderOf(filePath)
%IFOLDEROF Absolute folder of a path, for comparing locations.
d = dir(fileparts(filePath));
if isempty(d)
    folder = fileparts(filePath);
else
    folder = d(1).folder;
end
folder = regexprep(folder, '[\\/]+$', '');
end
