function outData = run_SpeckleMapping(SaveFolder, data, varargin)
%RUN_SPECKLEMAPPING Call SPECKLEMAPPING from the IOI library.
%
%   outData = run_SpeckleMapping(SaveFolder, data)
%   outData = run_SpeckleMapping(SaveFolder, data, 'Name', Value, ...)
%   info    = run_SpeckleMapping('pipelineInfo')
%
%   This wrapper calculates the spatial or temporal standard deviation of a
%   Laser Speckle Contrast Imaging dataset by calling the IOI-library
%   function SPECKLEMAPPING.
%
%   Inputs:
%       SaveFolder - Existing folder. Resolves a bare .dat file name and
%                    receives the TIFF map when bSaveMap is true.
%       data       - The speckle data, in one of two forms that also select
%                    the execution mode:
%                      * Name or path of a Y-X-T single-precision .dat file
%                        (a bare name is looked up in SaveFolder). The file
%                        is processed in chunks (Low-RAM mode).
%                      * Numeric Y-X-T array. It is processed in RAM
%                        (Standard mode): whole, with one STDFILT call, when
%                        the available RAM allows it, and in chunks
%                        otherwise.
%                    Other extensions, other layouts, UMT structs, and .umt
%                    files are not supported.
%
%   Name-Value parameters:
%       sType     - Standard-deviation mode.
%                   Allowed: 'Spatial', 'Temporal'
%                   Default: 'Temporal'
%
%       bSaveMap  - If true, save the TIFF map generated by SPECKLEMAPPING.
%                   Default: false
%
%       bLogScale - If true, apply -log10 transform.
%                   Default: false
%
%   Output:
%       outData   - UMT struct of kind "image" containing the speckle map
%                   (one Y-X entry named "SpeckleMap").
%
%   Notes:
%       - A .dat file is never loaded whole. An array is checked against the
%         available RAM by SPECKLEMAPPING and chunked only when it does not
%         fit.

% Defaults:
default_Output = 'SpeckleMap';

allowedSType = {'Spatial', 'Temporal'};

% -------------------------------------------------------------------------
% pipelineInfo query
% -------------------------------------------------------------------------
if nargin == 1 && (ischar(SaveFolder) || (isstring(SaveFolder) && isscalar(SaveFolder))) ...
        && strcmpi(strtrim(char(string(SaveFolder))), 'pipelineInfo')
    outData = localPipelineInfo();
    return
end

% -------------------------------------------------------------------------
% Input parsing
% -------------------------------------------------------------------------
p = inputParser;
p.FunctionName = mfilename;

addRequired(p, 'SaveFolder', @isfolder);
addRequired(p, 'data');

addParameter(p, 'sType', 'Temporal', ...
    @(x) (ischar(x) || (isstring(x) && isscalar(x))) && ...
    any(strcmpi(char(string(x)), allowedSType)));

addParameter(p, 'bSaveMap', false, ...
    @(x) islogical(x) && isscalar(x));

addParameter(p, 'bLogScale', false, ...
    @(x) islogical(x) && isscalar(x));

parse(p, SaveFolder, data, varargin{:});

SaveFolder = p.Results.SaveFolder;
sType = char(string(p.Results.sType));
bSaveMap = p.Results.bSaveMap;
bLogScale = p.Results.bLogScale;

% -------------------------------------------------------------------------
% Resolve and validate the input. The type of "data" selects the mode.
% -------------------------------------------------------------------------
if ischar(data) || (isstring(data) && isscalar(data))
    % Filename: Low-RAM mode.
    data = char(string(data));

    [dataFolder, dataStem, dataExt] = fileparts(data);
    assert(isempty(dataExt) || strcmpi(dataExt, '.dat'), ...
        'Umitoolbox:run_SpeckleMapping:UnsupportedInputFile', ...
        'Unsupported input file extension "%s". Only .dat files are supported.', dataExt);

    % A bare name is looked up in SaveFolder; a path is used as given.
    if isempty(dataFolder)
        dataPath = fullfile(SaveFolder, [dataStem '.dat']);
    else
        dataPath = fullfile(dataFolder, [dataStem '.dat']);
    end
    assert(isfile(dataPath), ...
        'Umitoolbox:run_SpeckleMapping:FileNotFound', ...
        'Input .dat file not found: "%s".', data);

    assertDatLayout(loadMetaData(dataPath), {{'Y','X','T'}}, 'run_SpeckleMapping');

    speckleInput = dataPath;
    mode = 'Low-RAM';
elseif isnumeric(data) || islogical(data)
    % Array: Standard mode.
    assert(ndims(data) == 3 && ~isempty(data), ...
        'Umitoolbox:run_SpeckleMapping:unsupportedLayout', ...
        'Array input must be a non-empty Y x X x T array.');

    speckleInput = data;
    mode = 'Standard';
else
    error('Umitoolbox:run_SpeckleMapping:UnsupportedInputType', ...
        ['Input "data" must be the name of a Y-X-T .dat file or a numeric ' ...
         'Y-X-T array.']);
end

% -------------------------------------------------------------------------
% Dispatch
% -------------------------------------------------------------------------
disp(['Calculating ' sType ' standard deviation (' mode ' mode)...'])

try
    outData = SpeckleMapping( ...
        speckleInput, ...
        SaveFolder, ...
        sType, ...
        bSaveMap, ...
        bLogScale);
catch ME
    ME = addCause(ME, MException( ...
        'Umitoolbox:run_SpeckleMapping:UnknownError', ...
        'Function SpeckleMapping failed.'));
    throw(ME)
end

disp('Finished Speckle Mapping.')

    % =====================================================================
    % Local pipelineInfo factory (nested, shares allowedSType/default_Output
    % with the parent scope instead of redefining them)
    % =====================================================================
    function info = localPipelineInfo()

        info = PipelineManager.createPipelineInfo( ...
            mfilename, ...
            'Call SPECKLEMAPPING from the IOI library to compute speckle standard-deviation maps.');
        info.version = '3.0.0';

        info = PipelineManager.addInput( ...
            info, ...
            'SaveFolder', ...
            'SaveFolder', ...
            'Folder used to resolve the input file and to save the optional TIFF map.', ...
            'kind', 'input', ...
            'position', 1, ...
            'callType', 'positional', ...
            'isData', false);

        info = PipelineManager.addInput( ...
            info, ...
            'data', ...
            'ImageTimeSeries', ...
            ['Y-X-T speckle data: a .dat file (Low-RAM mode) or a numeric ' ...
             'array (Standard mode).'], ...
            'kind', 'input', ...
            'position', 2, ...
            'callType', 'positional', ...
            'isData', true, ...
            'supportsFile', true, ...
            'dataMode', 'either');

        info = PipelineManager.addInput( ...
            info, ...
            'sType', ...
            'parameter', ...
            'Standard-deviation mode.', ...
            'kind', 'parameter', ...
            'default', 'Temporal', ...
            'allowed', allowedSType, ...
            'callType', 'namevalue');

        info = PipelineManager.addInput( ...
            info, ...
            'bSaveMap', ...
            'parameter', ...
            'If true, save the TIFF map generated by SPECKLEMAPPING.', ...
            'kind', 'parameter', ...
            'default', false, ...
            'allowed', [true false], ...
            'callType', 'namevalue');

        info = PipelineManager.addInput( ...
            info, ...
            'bLogScale', ...
            'parameter', ...
            'If true, apply -log10 transform.', ...
            'kind', 'parameter', ...
            'default', false, ...
            'allowed', [true false], ...
            'callType', 'namevalue');

        info = PipelineManager.addOutput( ...
            info, ...
            'outData', ...
            'ProcessedData', ...
            'data', ...
            'UMT image output containing the computed speckle map.', ...
            default_Output, ...
            1, ...
            'isData', true);

    end

end
