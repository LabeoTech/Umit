function [registration, referenceTemplate, estimateTemplate] = newRegistrationRecord()
%NEWREGISTRATIONRECORD Empty DataParams.registration (version 2).
%
%   [registration, referenceTemplate, estimateTemplate] = newRegistrationRecord()
%
%   DataParams.registration is the ONLY record of a folder's image reference
%   and alignment. Version 2 layout:
%
%   registration
%     .version    2
%     .reference  [] (none selected) or:
%         image           copy of the reference image (single, 2-D)
%         contentHash     computeImageContentHash(image)
%         name, description, axisConvention
%         imageSizeYX     size(image)
%         selectedOn      ISO-8601 text
%         source          descriptor (referenceSourceDescriptor; paths are
%                         human aids only)
%     .estimate   [] (no estimate) or:
%         tform, transformType, method
%         qcStatus, qcWarning, qcMetrics, qcFigureFile, qcPreviewImageFile
%         createdOn       ISO-8601 text
%         movingSource    file/context the moving image came from
%         referenceHash   the reference hash the estimate was made against
%     .apply      the apply record:
%         isRegistered, isReviewed (logical)
%         appliedOn, appliedBy, confirmationMode (text, '' until applied)
%         appliedReferenceHash  the COMMITMENT ('' until applied)
%         manualAdjustment (struct), notes (text)
%
%   Removed from version 1: referenceFile (replaced by reference.source),
%   imageReferenceUUID and imageReferenceChecksum (replaced by
%   reference.source + reference.contentHash), resourceUUID (registration-
%   transform resources are no longer written, brief section 4 Q5).
%
%   The templates are empty reference/estimate structs with every field.
%
%   See also validateRegistrationRecord, upgradeRegistrationRecord.

referenceTemplate = struct( ...
    'image', [], ...
    'contentHash', '', ...
    'name', '', ...
    'description', '', ...
    'axisConvention', 'imageXY_topLeft', ...
    'imageSizeYX', [], ...
    'selectedOn', '', ...
    'source', referenceSourceDescriptor('legacy', ''));

estimateTemplate = struct( ...
    'tform', [], ...
    'transformType', '', ...
    'method', '', ...
    'qcStatus', '', ...
    'qcWarning', '', ...
    'qcMetrics', struct('MIBefore', [], 'MIAfter', [], 'MIDelta', [], ...
        'translationXY_px', [], 'rotationDeg', [], 'scaleXY', [], 'determinant', []), ...
    'qcFigureFile', '', ...
    'qcPreviewImageFile', '', ...
    'createdOn', '', ...
    'movingSource', '', ...
    'referenceHash', '');

apply = struct( ...
    'isRegistered', false, ...
    'isReviewed', false, ...
    'appliedOn', '', ...
    'appliedBy', '', ...
    'confirmationMode', '', ...
    'appliedReferenceHash', '', ...
    'manualAdjustment', struct(), ...
    'notes', '');

registration = struct('version', 2, 'reference', [], 'estimate', [], 'apply', apply);
end
