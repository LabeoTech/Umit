function validateDataParams(DataParams)
%VALIDATEDATAPARAMS Validate structure and field consistency of DataParams.
%
%   validateDataParams(DataParams)
%
%   Checks whether DataParams follows the expected schema and verifies
%   consistency of folder-global fields such as image size, origin, mask,
%   and registration metadata.
%
%   Required top-level fields:
%       schemaVersion
%       createdOn
%       lastModified
%       notes
%       view
%       mask
%       folders
%       registration
%       cameraCoregistration
%       custom
%
%   Notes:
%       - This function throws an error when validation fails.
%       - Validation is intentionally permissive for optional fields.
%       - DataParams.registration is the version-2 record
%         (newRegistrationRecord / validateRegistrationRecord); loadDataParams
%         and saveDataParams upgrade a version-1 record in memory first.

if ~isstruct(DataParams) || ~isscalar(DataParams)
    error('validateDataParams:InvalidType', ...
        'DataParams must be a scalar struct.');
end

reqTopFields = { ...
    'schemaVersion', ...
    'createdOn', ...
    'lastModified', ...
    'notes', ...
    'view', ...
    'mask', ...
    'folders', ...
    'registration', ...
    'cameraCoregistration', ...
    'custom'};

for k = 1:numel(reqTopFields)
    if ~isfield(DataParams, reqTopFields{k})
        error('validateDataParams:MissingField', ...
            'Missing top-level field: DataParams.%s', reqTopFields{k});
    end
end

% =========================================================================
% View
% =========================================================================
if ~isstruct(DataParams.view) || ~isscalar(DataParams.view)
    error('validateDataParams:InvalidView', ...
        'DataParams.view must be a scalar struct.');
end

reqViewFields = { ...
    'pixelSize_px_per_mm', ...
    'origin_xy_px', ...
    'imageSizeYX', ...
    'axisConvention'};

for k = 1:numel(reqViewFields)
    if ~isfield(DataParams.view, reqViewFields{k})
        error('validateDataParams:MissingViewField', ...
            'Missing field: DataParams.view.%s', reqViewFields{k});
    end
end

if ~isempty(DataParams.view.pixelSize_px_per_mm)
    x = DataParams.view.pixelSize_px_per_mm;
    if ~isnumeric(x) || ~(isscalar(x) || numel(x) == 2) || ...
            any(~isfinite(x(:))) || any(x(:) <= 0)
        error('validateDataParams:InvalidPixelSize', ...
            ['DataParams.view.pixelSize_px_per_mm must be a positive ' ...
             'scalar or 2-element numeric vector.']);
    end
end

if ~isempty(DataParams.view.origin_xy_px)
    x = DataParams.view.origin_xy_px;
    if ~isnumeric(x) || numel(x) ~= 2 || any(~isfinite(x(:)))
        error('validateDataParams:InvalidOrigin', ...
            'DataParams.view.origin_xy_px must be a 2-element numeric vector [x y].');
    end
end

if ~isempty(DataParams.view.imageSizeYX)
    x = DataParams.view.imageSizeYX;
    if ~isnumeric(x) || numel(x) ~= 2 || any(~isfinite(x(:))) || ...
            any(x(:) <= 0) || any(mod(x(:),1) ~= 0)
        error('validateDataParams:InvalidImageSize', ...
            ['DataParams.view.imageSizeYX must be a positive integer ' ...
             '2-element vector [Ny Nx].']);
    end
end

if ~(ischar(DataParams.view.axisConvention) || ...
        (isstring(DataParams.view.axisConvention) && isscalar(DataParams.view.axisConvention)))
    error('validateDataParams:InvalidAxisConvention', ...
        'DataParams.view.axisConvention must be a char vector or string scalar.');
end

% =========================================================================
% Mask
% =========================================================================
if ~isstruct(DataParams.mask) || ~isscalar(DataParams.mask)
    error('validateDataParams:InvalidMask', ...
        'DataParams.mask must be a scalar struct.');
end

reqMaskFields = { ...
    'logical', ...
    'name', ...
    'description', ...
    'space', ...
    'createdOn', ...
    'source'};

for k = 1:numel(reqMaskFields)
    if ~isfield(DataParams.mask, reqMaskFields{k})
        error('validateDataParams:MissingMaskField', ...
            'Missing field: DataParams.mask.%s', reqMaskFields{k});
    end
end

if ~isempty(DataParams.mask.logical)
    if ~islogical(DataParams.mask.logical) || ...
            ~ismatrix(DataParams.mask.logical)
        error('validateDataParams:InvalidMaskLogical', ...
            'DataParams.mask.logical must be a 2D logical array.');
    end

    if ~isempty(DataParams.view.imageSizeYX)
        if ~isequal(size(DataParams.mask.logical), DataParams.view.imageSizeYX)
            error('validateDataParams:MaskSizeMismatch', ...
                'DataParams.mask.logical size must match DataParams.view.imageSizeYX.');
        end
    end
end

% =========================================================================
% Folders
% =========================================================================
if ~isstruct(DataParams.folders) || ~isscalar(DataParams.folders)
    error('validateDataParams:InvalidFolders', ...
        'DataParams.folders must be a scalar struct.');
end

reqFolderFields = { ...
    'RawFolder', ...
    'RawFolderStatus', ...
    'RawFolderSetOn', ...
    'RawFolderSetBy'};

for k = 1:numel(reqFolderFields)
    if ~isfield(DataParams.folders, reqFolderFields{k})
        error('validateDataParams:MissingFoldersField', ...
            'Missing field: DataParams.folders.%s', reqFolderFields{k});
    end
end

if ~(ischar(DataParams.folders.RawFolder) || ...
        (isstring(DataParams.folders.RawFolder) && isscalar(DataParams.folders.RawFolder)))
    error('validateDataParams:InvalidRawFolder', ...
        'DataParams.folders.RawFolder must be a char vector or string scalar.');
end

rawFolderText = char(string(DataParams.folders.RawFolder));
if isempty(rawFolderText)
    error('validateDataParams:InvalidRawFolder', ...
        'DataParams.folders.RawFolder cannot be empty. Use ''Missing'' instead.');
end

if ~(ischar(DataParams.folders.RawFolderStatus) || ...
        (isstring(DataParams.folders.RawFolderStatus) && isscalar(DataParams.folders.RawFolderStatus)))
    error('validateDataParams:InvalidRawFolderStatus', ...
        'DataParams.folders.RawFolderStatus must be a char vector or string scalar.');
end

statusText = lower(strtrim(char(string(DataParams.folders.RawFolderStatus))));
validStatus = {'valid', 'missing', 'invalid'};
if ~ismember(statusText, validStatus)
    error('validateDataParams:InvalidRawFolderStatus', ...
        'DataParams.folders.RawFolderStatus must be ''valid'', ''missing'', or ''invalid''.');
end

if strcmpi(rawFolderText, 'Missing') && ~strcmp(statusText, 'missing')
    error('validateDataParams:RawFolderStatusMismatch', ...
        'DataParams.folders.RawFolderStatus must be ''missing'' when RawFolder is ''Missing''.');
end

if strcmp(statusText, 'missing') && ~strcmpi(rawFolderText, 'Missing')
    error('validateDataParams:RawFolderStatusMismatch', ...
        'DataParams.folders.RawFolder must be ''Missing'' when RawFolderStatus is ''missing''.');
end

if ~(isempty(DataParams.folders.RawFolderSetOn) || ...
        (isdatetime(DataParams.folders.RawFolderSetOn) && isscalar(DataParams.folders.RawFolderSetOn)))
    error('validateDataParams:InvalidRawFolderSetOn', ...
        'DataParams.folders.RawFolderSetOn must be empty or a scalar datetime.');
end

if ~(isempty(DataParams.folders.RawFolderSetBy) || ...
        ischar(DataParams.folders.RawFolderSetBy) || ...
        (isstring(DataParams.folders.RawFolderSetBy) && isscalar(DataParams.folders.RawFolderSetBy)))
    error('validateDataParams:InvalidRawFolderSetBy', ...
        'DataParams.folders.RawFolderSetBy must be empty, a char vector, or a string scalar.');
end

% =========================================================================
% Registration (version 2; see newRegistrationRecord)
% =========================================================================
validateRegistrationRecord(DataParams.registration, DataParams.view);

% =========================================================================
% Dual-camera coregistration (rig-owned; resourceUUID/rigID may be empty)
% =========================================================================
if ~isstruct(DataParams.cameraCoregistration) || ~isscalar(DataParams.cameraCoregistration)
    error('validateDataParams:InvalidCameraCoregistration', ...
        'DataParams.cameraCoregistration must be a scalar struct.');
end

reqCamCoregFields = { ...
    'isCoregistered', ...
    'isReviewed', ...
    'tform', ...
    'resourceUUID', ...
    'rigID', ...
    'transformType', ...
    'method', ...
    'sourceFile', ...
    'sourceFileTimestamp', ...
    'createdOn', ...
    'source', ...
    'qcStatus', ...
    'qcWarning', ...
    'qcMetrics', ...
    'qcFigureFile', ...
    'qcPreviewImageFile', ...
    'appliedOn', ...
    'appliedBy', ...
    'confirmationMode', ...
    'notes'};

for k = 1:numel(reqCamCoregFields)
    if ~isfield(DataParams.cameraCoregistration, reqCamCoregFields{k})
        error('validateDataParams:MissingCameraCoregistrationField', ...
            'Missing field: DataParams.cameraCoregistration.%s', reqCamCoregFields{k});
    end
end

if ~islogical(DataParams.cameraCoregistration.isCoregistered) || ...
        ~isscalar(DataParams.cameraCoregistration.isCoregistered)
    error('validateDataParams:InvalidIsCoregistered', ...
        'DataParams.cameraCoregistration.isCoregistered must be a scalar logical.');
end

if ~islogical(DataParams.cameraCoregistration.isReviewed) || ...
        ~isscalar(DataParams.cameraCoregistration.isReviewed)
    error('validateDataParams:InvalidCameraCoregistrationIsReviewed', ...
        'DataParams.cameraCoregistration.isReviewed must be a scalar logical.');
end

if DataParams.cameraCoregistration.isCoregistered && ...
        isempty(DataParams.cameraCoregistration.tform)
    error('validateDataParams:MissingCameraCoregistrationTform', ...
        ['DataParams.cameraCoregistration.tform cannot be empty when ' ...
         'isCoregistered is true.']);
end

textCamCoregFields = { ...
    'resourceUUID', ...
    'rigID', ...
    'transformType', ...
    'method', ...
    'sourceFile', ...
    'sourceFileTimestamp', ...
    'createdOn', ...
    'source', ...
    'qcStatus', ...
    'qcWarning', ...
    'qcFigureFile', ...
    'qcPreviewImageFile', ...
    'appliedOn', ...
    'appliedBy', ...
    'confirmationMode', ...
    'notes'};

for k = 1:numel(textCamCoregFields)
    fieldName = textCamCoregFields{k};
    val = DataParams.cameraCoregistration.(fieldName);
    if ~(isempty(val) || ischar(val) || (isstring(val) && isscalar(val)))
        error('validateDataParams:InvalidCameraCoregistrationTextField', ...
            ['DataParams.cameraCoregistration.%s must be empty, a char vector, ' ...
             'or a string scalar.'], fieldName);
    end
end

if ~isstruct(DataParams.cameraCoregistration.qcMetrics) || ...
        ~isscalar(DataParams.cameraCoregistration.qcMetrics)
    error('validateDataParams:InvalidCameraCoregistrationQCMetrics', ...
        'DataParams.cameraCoregistration.qcMetrics must be a scalar struct.');
end

reqCamCoregQCMetricsFields = { ...
    'MIBefore', 'MIAfter', 'MIDelta', 'translationXY_px', ...
    'rotationDeg', 'scaleXY', 'determinant'};

for k = 1:numel(reqCamCoregQCMetricsFields)
    if ~isfield(DataParams.cameraCoregistration.qcMetrics, reqCamCoregQCMetricsFields{k})
        error('validateDataParams:MissingCameraCoregistrationQCMetricsField', ...
            'Missing field: DataParams.cameraCoregistration.qcMetrics.%s', ...
            reqCamCoregQCMetricsFields{k});
    end
end

if ~isempty(DataParams.cameraCoregistration.qcMetrics.scaleXY)
    if any(DataParams.cameraCoregistration.qcMetrics.scaleXY(:) <= 0)
        error('validateDataParams:InvalidCameraCoregistrationScaleXY', ...
            'DataParams.cameraCoregistration.qcMetrics.scaleXY must contain positive values.');
    end
end

if DataParams.cameraCoregistration.isReviewed && ...
        isempty(DataParams.cameraCoregistration.tform)
    error('validateDataParams:CameraCoregistrationReviewedWithoutTform', ...
        'Camera coregistration cannot be marked as reviewed when tform is empty.');
end

if ~isempty(DataParams.cameraCoregistration.appliedOn) && ...
        ~DataParams.cameraCoregistration.isCoregistered
    error('validateDataParams:CameraCoregistrationAppliedOnWithoutFlag', ...
        ['DataParams.cameraCoregistration.appliedOn cannot be populated when ' ...
         'isCoregistered is false.']);
end

if ~isempty(DataParams.cameraCoregistration.appliedBy) && ...
        ~DataParams.cameraCoregistration.isCoregistered
    error('validateDataParams:CameraCoregistrationAppliedByWithoutFlag', ...
        ['DataParams.cameraCoregistration.appliedBy cannot be populated when ' ...
         'isCoregistered is false.']);
end

if ~isempty(DataParams.cameraCoregistration.confirmationMode) && ...
        ~DataParams.cameraCoregistration.isCoregistered
    error('validateDataParams:CameraCoregistrationConfirmationModeWithoutFlag', ...
        ['DataParams.cameraCoregistration.confirmationMode cannot be populated ' ...
         'when isCoregistered is false.']);
end

end
