function descriptor = referenceSourceDescriptor(kind, path)
%REFERENCESOURCEDESCRIPTOR Empty source descriptor of an image reference.
%
%   descriptor = referenceSourceDescriptor(kind, path)
%
%   The descriptor records where a reference came from, for humans only:
%   UMIT never resolves its paths again (identity and verification use the
%   image and its content hash). It is stored in
%   DataParams.registration.reference.source. Every kind has the same flat
%   field set; fields that do not apply to a kind stay empty.
%
%   Fields:
%       kind                   'project', 'umitDat', 'file' or 'legacy'
%                              ('legacy': upgraded from a v1 DataParams
%                              record whose source is unknown)
%       path                   store file / .dat file / reference file path
%       projectUUID, projectName, subjectUUID, subjectID,
%       sessionUUID, sessionID  identity (project kind; file kind when the
%                              exported file carries it)
%       resourceUUID           library resource (project kind)
%       saveFolder             SaveFolder of the .dat (umitDat kind)
%       extractionRule,
%       extractionRuleVersion  fixed .dat extraction rule (umitDat kind)
%       sourceAligned          the source folder was already aligned
%       sourceCommittedHash,
%       sourceCommittedName    that folder's committed reference
%       fileFormat             'umitReference' or 'image' (file kind)
%       entry                  MAT variable / UMT entry read (file kind)
%       warning                the aligned-source warning, '' if none
%
%   See also resolveImageReferenceSource, validateReferenceSourceDescriptor.

kinds = {'project', 'umitDat', 'file', 'legacy'};
kind = char(string(kind));
if ~ismember(kind, kinds)
    error('Umitoolbox:ImageRegistration:invalidSource', ...
        'Unknown reference source kind "%s".', kind);
end

descriptor = struct( ...
    'kind', kind, ...
    'path', char(string(path)), ...
    'projectUUID', '', ...
    'projectName', '', ...
    'subjectUUID', '', ...
    'subjectID', '', ...
    'sessionUUID', '', ...
    'sessionID', '', ...
    'resourceUUID', '', ...
    'saveFolder', '', ...
    'extractionRule', '', ...
    'extractionRuleVersion', [], ...
    'sourceAligned', false, ...
    'sourceCommittedHash', '', ...
    'sourceCommittedName', '', ...
    'fileFormat', '', ...
    'entry', '', ...
    'warning', '');
end
